export function getMovieById(id: number): (MovieWithProviders & { isUpcoming?: boolean }) | undefined {
  return CURATED_MOVIES.find((m) => m.id === id);
}

export function getMoviesByHero(heroName: string): (MovieWithProviders & { isUpcoming?: boolean })[] {
  return CURATED_MOVIES.filter((m) => m.hero_name?.toLowerCase().includes(heroName.toLowerCase()));
}

export function getKannadaOriginals(): (MovieWithProviders & { isUpcoming?: boolean })[] {
  return CURATED_MOVIES.filter((m) => m.isKannada);
}

export function getKannadaDubbed(): (MovieWithProviders & { isUpcoming?: boolean })[] {
  return CURATED_MOVIES.filter((m) => !m.isKannada && m.hasKannadaDub);
}

export function getMoviesByProvider(providerId: number): (MovieWithProviders & { isUpcoming?: boolean })[] {
  return CURATED_MOVIES.filter((m) =>
    m.watchProviders?.flatrate?.some((p) => p.provider_id === providerId)
  );
}

export function searchCatalog(query: string): (MovieWithProviders & { isUpcoming?: boolean })[] {
  const q = query.toLowerCase();
  return CURATED_MOVIES.filter(
    (m) =>
      m.title.toLowerCase().includes(q) ||
      m.original_title.toLowerCase().includes(q) ||
      m.hero_name?.toLowerCase().includes(q) ||
      m.director?.toLowerCase().includes(q) ||
      m.cast?.some((c) => c.toLowerCase().includes(q))
  );
}

export function getCatalogMovieDetails(id: number): MovieDetails | undefined {
  const m = getMovieById(id);
  if (!m) return undefined;
  return {
    ...m,
    genres: m.genre_ids.map((gid) => ({ id: gid, name: gid === 35 ? 'Comedy' : gid === 28 ? 'Action' : gid === 10749 ? 'Romance' : 'Drama' })),
    runtime: 145,
    tagline: m.highlights?.[0] || '',
    status: m.isUpcoming ? 'In Production / Releasing Soon' : 'Released',
    budget: 0,
    revenue: 0,
    homepage: m.watchProviders?.link || '',
    imdb_id: `tt${m.id}`,
    spoken_languages: [{ english_name: 'Kannada', iso_639_1: 'kn', name: 'ಕನ್ನಡ' }],
    production_countries: [{ iso_3166_1: 'IN', name: 'India' }],
  };
}
